import { open, go, shot, cardOf, pick } from './cap.mjs';
const { browser, page } = await open('state-owner.json');
const T = (t) => page.getByText(t, { exact: false }).first();
const B = (n) => page.getByRole('button', { name: n }).first();
const L = (n) => page.getByLabel(n, { exact: false }).first();

await go(page, '/dashboard');
await shot(page, 'tour-kpis', page.locator('div', { has: T('Receita (30 dias)') }).filter({ has: T('Giro de estoque') }).last());
await shot(page, 'tour-unidade', page.locator('aside').getByText('Bonsucesso Varejo').first().locator('xpath=ancestor::*[self::button or self::div][2]'));
await page.keyboard.press('Control+k'); await page.waitForTimeout(600);
await page.keyboard.type('transf'); await page.waitForTimeout(800);
await shot(page, 'busca-paleta', page.getByPlaceholder(/Buscar produtos, telas/).locator('xpath=ancestor::div[3]'));
await page.keyboard.press('Escape');
await go(page, '/notifications');
await shot(page, 'notificacoes-lista', T('Não lidas').locator('xpath=ancestor::div[1]'));
await go(page, '/products/new');
await page.locator('button', { hasText: 'Vestuário' }).first().click(); await page.waitForTimeout(500);
await shot(page, 'produto-categoria', page.locator('button', { hasText: 'Vestuário' }).first().locator('xpath=ancestor::div[contains(@class,"card")][1]'));
await go(page, '/stock/entry/ocr');
await shot(page, 'ocr-fonte', T('Foto da nota').locator('xpath=ancestor::div[2]'));
await go(page, '/products/pricing');
await L('Fornecedor').selectOption({ label: 'TechDistrib' }).catch(async () => { await page.locator('select').first().selectOption({ index: 1 }); });
await page.waitForTimeout(400);
const pct = page.getByLabel(/Percentual/).first(); if (await pct.count()) { await pct.fill('8'); }
await page.waitForTimeout(1500);
await shot(page, 'reajuste-simulacao', cardOf(page, 'Simulação'));
await go(page, '/stock/sale');
await pick(page, 'tenis', 'CAL-TENISE-PR-40');
await B(/Dividir em outra forma/).click().catch(() => {}); await page.waitForTimeout(500);
await shot(page, 'venda-pagamento', page.getByLabel('Forma 1').locator('xpath=ancestor::div[contains(@class,"card")][1]'));
await go(page, '/cash');
await shot(page, 'caixa-fechamento', T('Vendas do turno').locator('xpath=ancestor::div[contains(@class,"card")][1]'));
await shot(page, 'caixa-contagem', cardOf(page, 'Contagem de gaveta'));
await go(page, '/stock/count');
await shot(page, 'contagem-escopo', cardOf(page, 'Escopo da contagem'));
await pick(page, 'pendrive', 'ELE-PENDRI-PR-64'); await pick(page, 'pendrive', 'ELE-PENDRI-PR-128');
const inputs = page.locator('tbody input'); if (await inputs.count()) { await inputs.nth(0).fill('44'); if (await inputs.count() > 1) await inputs.nth(1).fill('31'); }
await page.waitForTimeout(500);
await shot(page, 'contagem-itens', cardOf(page, 'Ficha de contagem'));
await shot(page, 'contagem-fechar', B(/Fechar contagem/));
await go(page, '/purchase-orders');
const boxes = page.locator('tbody input[type=checkbox]');
if (await boxes.count()) await boxes.first().check().catch(() => {});
await B(/Gerar pedido/).click().catch(() => {}); await page.waitForTimeout(2500);
await shot(page, 'pedido-form', B(/Registrar pedido/));
await go(page, '/promotions');
await shot(page, 'promocoes-lista', page.locator('main').getByText('Criar promoção').first());
await go(page, '/ai'); await shot(page, 'ia-hub', T('Uso por recurso').locator('xpath=ancestor::div[2]'));
await go(page, '/ai/anomalies'); await shot(page, 'ia-anomalias', page.getByRole('button', { name: /Repor agora/ }).first().locator('xpath=ancestor::div[3]'));
await go(page, '/products/import');
await page.locator('input[type=file]').first().setInputFiles('importacao-exemplo.csv'); await page.waitForTimeout(2500);
await shot(page, 'importar-revisar', cardOf(page, 'Linhas com erro'));
await browser.close();
