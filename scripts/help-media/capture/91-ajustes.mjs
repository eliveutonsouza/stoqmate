import { open, go, shot, cardOf } from './cap.mjs';
const { browser, page } = await open('state-owner.json');
const B = (n) => page.getByRole('button', { name: n }).first();
await go(page, '/dashboard');
await page.keyboard.press('Control+k'); await page.waitForTimeout(600);
await page.keyboard.type('transf'); await page.waitForTimeout(800);
const inp = page.getByPlaceholder(/Buscar produtos, telas/);
await shot(page, 'busca-paleta', page.locator('xpath=//*').filter({ has: inp }).last());
await page.keyboard.press('Escape');
await go(page, '/products/import');
await page.locator('input[type=file]').first().setInputFiles('importacao-exemplo.csv'); await page.waitForTimeout(1500);
await B(/Continuar/).click(); await page.waitForTimeout(2500);
await shot(page, 'importar-revisar', cardOf(page, 'Linhas com erro'));
await go(page, '/purchase-orders');
const boxes = page.locator('tbody input[type=checkbox]'); if (await boxes.count()) await boxes.first().check().catch(() => {});
await B(/Gerar pedido/).click().catch(() => {}); await page.waitForTimeout(2500);
await shot(page, 'pedido-form', cardOf(page, 'Fornecedor e entrega'));
await go(page, '/promotions');
await shot(page, 'promocoes-lista', B(/Criar promoção/));
await browser.close();
