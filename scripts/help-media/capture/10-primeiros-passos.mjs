import { open, go, shot, cardOf } from './cap.mjs';
const { browser, page } = await open('state-owner.json');
const T = (t) => page.getByText(t, { exact: false }).first();
const B = (n) => page.getByRole('button', { name: n }).first();
const dialog = () => page.locator('[role=dialog]').first();

await go(page, '/dashboard');
await shot(page, 'tour-menu', page.locator('aside').first());
await shot(page, 'tour-kpis', page.locator('.card', { has: T('Receita (30 dias)') }).filter({ has: T('Giro de estoque') }).last());
await shot(page, 'tour-acoes', cardOf(page, 'Ações rápidas'));
await shot(page, 'tour-unidade', page.locator('aside').getByText('Loja Centro').first().locator('..').locator('..'));
await shot(page, 'tour-conta', page.locator('aside').getByText('Ana Ribeiro').first().locator('..').locator('..'));
await page.keyboard.press('Control+k'); await page.waitForTimeout(600);
await page.keyboard.type('transf'); await page.waitForTimeout(800);
await shot(page, 'busca-paleta', dialog());
await page.keyboard.press('Escape');
await go(page, '/notifications');
await shot(page, 'notificacoes-lista', T('Estoque abaixo do mínimo'));
await go(page, '/settings/notifications');
await shot(page, 'notificacoes-regras', cardOf(page, 'Regras de aviso'));
await go(page, '/profile');
await shot(page, 'perfil-dados', cardOf(page, 'Dados pessoais'));
await shot(page, 'perfil-senha', cardOf(page, 'Senha atual'));
await shot(page, 'perfil-2fa', cardOf(page, 'duas etapas'));
await go(page, '/first-run');
await shot(page, 'checklist', cardOf(page, 'Cadastrar os produtos'));
await go(page, '/settings/units');
await shot(page, 'unidades-lista', B(/Adicionar unidade/));
await B(/Adicionar unidade/).click(); await page.waitForTimeout(600);
await shot(page, 'unidades-nova', dialog());
await page.keyboard.press('Escape');
await go(page, '/settings/users');
await shot(page, 'equipe-lista', B(/Convidar usuário/));
await B(/Convidar usuário/).click(); await page.waitForTimeout(600);
await shot(page, 'equipe-convidar', dialog());
await page.keyboard.press('Escape');
await go(page, '/settings/roles');
await shot(page, 'cargos-matriz');
await shot(page, 'cargos-simular', cardOf(page, 'Simular'));
await browser.close();
