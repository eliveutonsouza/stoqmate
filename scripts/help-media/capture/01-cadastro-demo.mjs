import { chromium } from 'playwright';
import { withLocalFonts } from './fonts.mjs';
const pw = (process.env.DEMO_PASSWORD ?? '');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await withLocalFonts(ctx);
const p = await ctx.newPage();
p.on('console', (m) => { if (m.type() === 'error') console.log('console.error:', m.text().slice(0, 200)); });
await p.goto('http://localhost:3100/signup');
await p.getByPlaceholder('Seu nome completo').fill('Ana Ribeiro');
await p.getByPlaceholder('voce@sualoja.com.br').fill('demo-ajuda@stoqmate-qa.com.br');
await p.getByPlaceholder('••••••••').fill(pw);
await p.getByPlaceholder('Ex.: Loja Centro').fill('Bonsucesso Varejo');
await p.getByRole('button', { name: /Rede/ }).first().click();
await p.locator('input[type=checkbox]').check();
await p.locator('button[type=submit]').click();
await p.waitForURL(/onboarding|verify|dashboard/, { timeout: 30000 }).catch(() => {});
await p.waitForTimeout(2000);
console.log('url', p.url());
await p.screenshot({ path: 'after-signup.png' });
await ctx.storageState({ path: 'state-owner.json' });
await b.close();
